const DEFAULT_LEAD_IN_SECONDS = 3;
const MAX_CONTIGUOUS_GAP_SECONDS = 0.35;
const MIN_CONTIGUOUS_OVERLAP_SECONDS = -0.1;

export function resolveSentencePlaybackRange({ sentence, sentences, mediaDuration = Infinity } = {}) {
  const displayStart = Math.max(0, Number(sentence?.start) || 0);
  const displayEnd = Math.max(displayStart, Number(sentence?.end) || displayStart);
  const hasAlignedPlayback = Number.isFinite(Number(sentence?.playbackStart))
    && Number.isFinite(Number(sentence?.playbackEnd))
    && Number(sentence.playbackEnd) > Number(sentence.playbackStart);
  const safeMediaEnd = Number.isFinite(Number(mediaDuration))
    ? Math.max(0, Number(mediaDuration))
    : Infinity;
  const requestedStart = hasAlignedPlayback ? Math.max(0, Number(sentence.playbackStart)) : displayStart;
  const requestedEnd = hasAlignedPlayback
    ? Math.max(requestedStart, Number(sentence.playbackEnd))
    : displayEnd;
  const contentStart = Math.min(requestedStart, safeMediaEnd);
  const contentEnd = Math.max(contentStart, Math.min(requestedEnd, safeMediaEnd));
  const standard = {
    start: roundTime(contentStart),
    contentStart: roundTime(contentStart),
    contentEnd: roundTime(contentEnd),
    end: roundTime(Math.min(contentEnd, safeMediaEnd)),
    expanded: false,
    previousSentenceId: null,
    nextSentenceId: null,
  };
  // Estimated display timestamps are intentionally not expanded to whole
  // neighbouring sentences. Accurate original-audio bounds are generated by
  // the Whisper alignment step and stored independently on the sentence.
  return standard;
}

// A sentence split from a speaker block has only a proportional display
// timestamp until Whisper finds the actual words. That estimate is useful for
// ordering the transcript, but it is not safe enough for a sentence-level
// play button: a missing/duplicate transcript sentence can otherwise play an
// unrelated fragment from the same block.
export function hasReliableSentencePlayback(sentence, mediaDuration = Infinity) {
  const hasAlignedPlayback = hasPlaybackBounds(sentence);
  if (!hasAlignedPlayback) return false;

  const requestedStart = Number(sentence.playbackStart);
  const requestedEnd = Number(sentence.playbackEnd);
  const numericDuration = Number(mediaDuration);
  const safeMediaEnd = Number.isFinite(numericDuration) && numericDuration > 0
    ? numericDuration
    : Infinity;
  const contentStart = Math.max(0, Math.min(requestedStart, safeMediaEnd));
  const contentEnd = Math.max(contentStart, Math.min(requestedEnd, safeMediaEnd));
  return contentEnd - contentStart >= 0.05;
}

export function resolveParagraphPlaybackRange({ unit, sentences, mediaDuration = Infinity } = {}) {
  const displayStart = Math.max(0, Number(unit?.start) || 0);
  const displayEnd = Math.max(displayStart, Number(unit?.end) || displayStart);
  const sentenceById = new Map((Array.isArray(sentences) ? sentences : []).map((sentence) => [sentence.id, sentence]));
  const targetSentences = (Array.isArray(unit?.sentenceIds) ? unit.sentenceIds : [])
    .map((id) => sentenceById.get(id))
    .filter(Boolean);
  const firstSentence = targetSentences[0];
  const lastSentence = targetSentences.at(-1);
  const alignedRanges = targetSentences
    .filter(hasPlaybackBounds)
    .map((sentence) => resolveSentencePlaybackRange({ sentence, sentences, mediaDuration }));
  const firstRange = firstSentence
    ? resolveSentencePlaybackRange({ sentence: firstSentence, sentences, mediaDuration })
    : null;
  const lastRange = lastSentence
    ? resolveSentencePlaybackRange({ sentence: lastSentence, sentences, mediaDuration })
    : null;
  const firstIsAligned = hasPlaybackBounds(firstSentence);
  const lastIsAligned = hasPlaybackBounds(lastSentence);
  const safeMediaEnd = Number.isFinite(Number(mediaDuration))
    ? Math.max(0, Number(mediaDuration))
    : Infinity;
  const earliestAlignedStart = alignedRanges.length
    ? Math.min(...alignedRanges.map((range) => range.start))
    : displayStart;
  const latestAlignedEnd = alignedRanges.length
    ? Math.max(...alignedRanges.map((range) => range.end))
    : displayEnd;
  const requestedStart = firstIsAligned
    ? firstRange.start
    : Math.min(displayStart, earliestAlignedStart);
  const contentStart = Math.min(requestedStart, safeMediaEnd);
  const requestedEnd = lastIsAligned
    ? lastRange.end
    : Math.max(displayEnd, latestAlignedEnd);
  const contentEnd = Math.max(
    contentStart,
    Math.min(requestedEnd, safeMediaEnd),
  );
  const trailingEnd = Math.max(contentEnd, Math.min(Math.max(0, Number(unit?.playbackEnd) || 0), safeMediaEnd));

  return {
    start: roundTime(contentStart),
    contentStart: roundTime(contentStart),
    contentEnd: roundTime(contentEnd),
    end: roundTime(trailingEnd),
    alignedStart: firstIsAligned,
    alignedEnd: lastIsAligned,
  };
}

export function resolveParagraphLeadIn({
  unit,
  paragraphs,
  maxSeconds = DEFAULT_LEAD_IN_SECONDS,
  maxGapSeconds = MAX_CONTIGUOUS_GAP_SECONDS,
} = {}) {
  const none = { start: Number(unit?.start) || 0, seconds: 0, previousParagraphId: null };
  if (!unit || !Array.isArray(paragraphs) || paragraphs.length < 2) return none;
  const index = paragraphs.findIndex((paragraph) => paragraph.id === unit.id);
  if (index <= 0) return none;

  const previous = paragraphs[index - 1];
  const currentStart = Number(unit.start);
  const previousStart = Number(previous.start);
  const previousEnd = Number(previous.end);
  if (![currentStart, previousStart, previousEnd].every(Number.isFinite) || previousStart >= currentStart) return none;
  if (normalizedSpeaker(previous.speaker) !== normalizedSpeaker(unit.speaker)) return none;
  if (!sharesSourceBlock(previous, unit)) return none;

  const gap = currentStart - previousEnd;
  if (gap < MIN_CONTIGUOUS_OVERLAP_SECONDS || gap > maxGapSeconds) return none;
  const safeMaximum = Math.max(0, Number(maxSeconds) || DEFAULT_LEAD_IN_SECONDS);
  const start = Math.max(previousStart, currentStart - safeMaximum, 0);
  const seconds = Math.max(0, currentStart - start);
  if (seconds < 0.15) return none;
  return {
    start: roundTime(start),
    seconds: roundTime(seconds),
    previousParagraphId: previous.id,
  };
}

export function playbackTargetCompletion(range, currentTime) {
  if (!range) return 0;
  const start = Number(range.contentStart ?? range.start);
  const end = Number(range.contentEnd ?? range.end);
  const time = Number(currentTime);
  if (![start, end, time].every(Number.isFinite) || end <= start) return 0;
  return Math.max(0, Math.min(1, (time - start) / (end - start)));
}

export function playbackLeadInRatio(range) {
  if (!range) return 0;
  const start = Number(range.start);
  const contentStart = Number(range.contentStart ?? range.start);
  const end = Number(range.end);
  if (![start, contentStart, end].every(Number.isFinite) || end <= start || contentStart <= start) return 0;
  return Math.max(0, Math.min(1, (contentStart - start) / (end - start)));
}

function normalizedSpeaker(value) {
  return String(value || "").trim().toLocaleLowerCase();
}

function sharesSourceBlock(left, right) {
  const leftIds = sourceBlockIds(left);
  const rightIds = sourceBlockIds(right);
  return leftIds.size > 0 && [...leftIds].some((id) => rightIds.has(id));
}

function sourceBlockIds(paragraph) {
  return new Set([
    paragraph?.sourceBlockId,
    ...(Array.isArray(paragraph?.sourceBlockIds) ? paragraph.sourceBlockIds : []),
  ].filter(Boolean).map(String));
}

function hasPlaybackBounds(sentence) {
  return hasPositiveRange(sentence?.playbackStart, sentence?.playbackEnd);
}

function hasPositiveRange(start, end) {
  return Number.isFinite(Number(start))
    && Number.isFinite(Number(end))
    && Number(end) > Number(start);
}

function roundTime(value) {
  return Math.round(value * 1000) / 1000;
}
